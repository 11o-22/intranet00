epicEnter = function () {
    if (!er) return;
    const key = er.place;
    const set = EPIC_SCENES[key];
    if (!set) { epicStub(); return; }

    if (!er.seen) er.seen = {};
    const job = er.job, attr = epicAttr();

    const pools = [];
    if (set.job && set.job[job]) pools.push(['j', set.job[job]]);
    if (set.attr && set.attr[attr]) pools.push(['a', set.attr[attr]]);
    if (set.common) pools.push(['c', set.common]);

    for (const [tag, arr] of pools) {
        for (let i = 0; i < arr.length; i++) {
            const id = `${key}:${tag}:${i}`;
            if (er.seen[id]) continue;
            er.seen[id] = true;
            er._scId = id;
            epicScene(arr[i]);
            return;
        }
    }
    epicStub();
};

