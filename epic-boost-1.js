// 배열이 없으면 만든다
function epicSlot(place, job) {
    if (!EPIC_SCENES[place]) EPIC_SCENES[place] = {};
    if (!EPIC_SCENES[place].job) EPIC_SCENES[place].job = {};
    if (!EPIC_SCENES[place].job[job]) EPIC_SCENES[place].job[job] = [];
    return EPIC_SCENES[place].job[job];
}

