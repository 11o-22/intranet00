// 칸이 없는 펫 — 태어난 때와 번호로 해시를 뜬다 (어디서 보든 같다)
function hash(key, s) {
    let h = 2166136261;
    const str = String(key) + '|' + String((s && s.at) || 0);
    for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; }
    return h;
}
function sexOf(key, u) {
    const s = P().pets(u)[String(key)];
    if (!s) return '';
    if (s.sex === 'm' || s.sex === 'f') return s.sex;
    return (hash(key, s) & 1) ? 'm' : 'f';
}
function perOf(key, u) {
    const s = P().pets(u)[String(key)];
    if (!s) return 0;
    const v = Number(s.per);
    if (v >= 0 && v <= 9 && Math.floor(v) === v) return v;
    return (hash(key, s) >>> 1) % 10;
}
function perName(key, u) {
    const list = PER[Number(key)] || PER[1];
    return list[perOf(key, u)] || '';
}
function sexName(sex) { return sex === 'm' ? '♂ 수컷' : sex === 'f' ? '♀ 암컷' : '?'; }
function skillOf(key) { return SKILL[Number(key)] || null; }

