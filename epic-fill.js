function epicTextCheck() {
    if (typeof EPIC_SCENES === 'undefined') { console.error('EPIC_SCENES 없음'); return; }
    const bad = [];
    Object.keys(EPIC_SCENES).forEach(function (z) {
        const j = EPIC_SCENES[z] && EPIC_SCENES[z].job;
        if (!j) return;
        Object.keys(j).forEach(function (k) {
            (j[k] || []).forEach(function (sc) {
                (sc.opts || []).forEach(function (o, oi) {
                    if (o.dc == null || o.doom) return;
                    if (!o.good) bad.push({ 구역: z, 직업: k, 장면: sc.title, 선택: oi + 1, 빠진것: 'good' });
                    if (!o.bad)  bad.push({ 구역: z, 직업: k, 장면: sc.title, 선택: oi + 1, 빠진것: 'bad' });
                });
            });
        });
    });
    if (!bad.length) { console.log('%c빠진 글이 없습니다.', 'color:#4CAF50; font-size:13px'); return; }
    console.warn('아직 빠진 글 ' + bad.length + '건');
    console.table(bad);
}