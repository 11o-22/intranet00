// 장면 이름으로 정해진 하나를 고른다 — 같은 장면은 항상 같은 글
function epicBadPick(job, title, idx) {
    const pool = EPIC_BAD[job] || EPIC_BAD_ANY;
    let h = 2166136261;
    const s = String(job) + '|' + String(title) + '|' + idx;
    for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
    return pool[(h >>> 0) % pool.length];
}

(function fillEpicBad() {
    if (typeof EPIC_SCENES === 'undefined') {
        console.warn('[??? 장면] EPIC_SCENES 가 먼저 올라와야 합니다.');
        return;
    }
    let filled = 0, skipped = 0;

    Object.keys(EPIC_SCENES).forEach(function (z) {
        const jobs = EPIC_SCENES[z] && EPIC_SCENES[z].job;
        if (!jobs) return;
        Object.keys(jobs).forEach(function (k) {
            (jobs[k] || []).forEach(function (sc) {
                (sc.opts || []).forEach(function (o, oi) {
                    if (o.dc == null) return;      // 판정 없는 선택지
                    if (o.doom) return;            // 실패가 doom 으로 빠지는 선택지
                    if (!o.bad) {
                        o.bad = epicBadPick(k, sc.title, oi);
                        if (o.poll == null) o.poll = 6;
                        filled++;
                    }
                    if (!o.good) { o.good = o.bad; skipped++; }
                });
            });
        });
    });

    console.log('[??? 장면] 실패 글 ' + filled + '자리 채움'
        + (skipped ? ' · 성공 글 ' + skipped + '자리 임시 대체' : ''));
})();

