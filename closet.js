    box.style.height = (D.H * k) + 'px';

    const sheets = (L.backs || []).concat([L.body]).concat(L.layers).concat([L.head]).concat(L.tops || []);
    const headAt = (L.backs || []).length + 1 + L.layers.length;   // 머리가 몇 번째 층인가 (몸 뒤에 깐 장까지 센다)
