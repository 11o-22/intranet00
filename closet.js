const ACC_CATS = ['머리', '귀', '얼굴', '목', '손', '등', '다리', '그 밖'];   // 다리 — 바니걸 스타킹 (2026-11-08)

function esc_(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
        return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
}
function btn(kind, key, val, text, on) {
    return '<button class="cl-b' + (on ? ' on' : '') + '" data-kind="' + kind
        + '" data-k="' + esc_(key) + '" data-v="' + esc_(val) + '">' + esc_(text) + '</button>';
}
function rowOf(lab, inner, extra) {
    return '<div class="cl-row"><span class="lab">' + esc_(lab) + '</span>'
        + '<div class="pick">' + inner + (extra || '') + '</div></div>';
}

function buildRows(u) {
    const p = cur();
    let html = '';

    // ① 얼굴
    html += '<div class="cl-h">얼굴</div>'
        // ★ 어둠 전용 머리는 어둠 소속에게만 보인다.
        //   다만 **지금 쓰고 있는 머리**는 소속이 바뀌었더라도 그대로 보여
        //   준다 — 안 그러면 제 얼굴이 목록에서 사라져 아무것도 눌린 데가
        //   없어 보인다.
        + rowOf('머리', DOT_HEADS.filter(function (h) {
            return allowed(h, u) || h.i === p.head;
        }).map(function (h) {
            return btn('head', 'head', h.i, h.n, h.i === p.head);
        }).join(''));

    // ② 의상 — 부위마다 한 줄
    let wear = '';
    DOT_SLOTS.forEach(function (s) {
        if (s.max) return;                       // 악세는 아래에서 따로
        const list = items(s, u).filter(function (x) { return !x.hide; });   // hide — 옷장에는 안 보이는 칸 (풀어진 셔츠)
        if (list.length < 2) return;             // 고를 것이 하나뿐이면 줄을 안 만든다
        wear += rowOf(s.n, list.map(function (x) {
            return btn('one', s.k, x.i, x.n, x.i === (p[s.k] || ''));
        }).join(''));
    });
    html += '<div class="cl-h">의상</div>' + (wear
        || '<div class="cl-none">갈아입을 것이 없습니다.</div>');

    // ③ 악세 — 다는 자리(머리·귀·얼굴·목·손·등)로 갈라 놓는다
    const s = slotOf('acc');
    if (s) {
        const max = s.max || 1;
        const sel = accSplit(p[s.k]);
        const on = items(s, u);
        const none = on.filter(function (x) { return !x.i; });
        const wearables = on.filter(function (x) { return x.i; });
        let acc = '';
        if (wearables.length) {
            acc += rowOf('벗기',
                btn('acc', s.k, '', (none[0] && none[0].n) || '없음', sel.length === 0),
                '<span class="cnt">' + sel.length + ' / ' + max + '</span>');
            ACC_CATS.forEach(function (c) {
                const list = wearables.filter(function (x) { return (x.cat || '그 밖') === c; });
                if (!list.length) return;
                acc += rowOf(c, list.map(function (x) {
                    return btn('acc', s.k, x.i, x.n, sel.indexOf(x.i) >= 0);
                }).join(''));
            });
        }
        html += '<div class="cl-h">악세 <i>' + max + '개까지</i></div>'
            + (acc || '<div class="cl-none">가진 악세가 없습니다.</div>');
    }

    // ④ 색 — 지금 입은 것마다 한 알씩. 누르면 색고리가 뜬다 (palette.js)
    //    ★ 물들이는 데에는 [ 🎨 컬러 팔레트 ] 가 한 개 든다. 되돌리는 것은 공짜다.
    if (typeof window.dotPalette === 'function') {
        html += '<div class="cl-h">색 <i>🎨 컬러 팔레트 한 개</i></div>'
            + '<div id="closet-cols">' + colHtml() + '</div>';
    }
    // ⑤ 불투명도 — 지금 입은 여성 체형 옷마다 하나씩 (2026-11-09). 여성 체형 옷을 입었을 때만 보인다.
    html += '<div id="closet-ops">' + opHtml() + '</div>';
    return html;
}

// ★ 불투명도 (2026-11-09 사용자 「여성 체형 의상 불투명도도 조절할 수 있는 기능 넣어줘」)
//   지금 입고 그려지는 여성 체형 옷(fem)마다 막대 하나 — 10 ~ 100 (10씩). 옷 열쇠(gk || i)마다 pick.op 에 적고,
//   [ 갈아입기 ] 를 누르면 me.dot.op 로 간다 (commit). 광장은 u.dot 을 통째로 주고받으므로 남의 화면에도 같다.
function wornFem(dotv) {
    const u = Object.assign({}, u_() || {}, { dot: dotv });
    const L = look(u);
    const drawn = {};
    (L.backs || []).concat(L.layers || [], L.tops || []).forEach(function (o) { drawn[o] = 1; });
    const out = [], seen = {};
    DOT_SLOTS.forEach(function (sl) {
        const ids = sl.max ? accSplit(dotv[sl.k]) : [dotv[sl.k] || ''];
        ids.forEach(function (id) {
            const it = sl.items.filter(function (x) { return x.i === id; })[0];
            if (!it || !it.fem) return;
            const sh = (it.back || []).concat(it.over || [], it.top || []);
            if (!sh.some(function (o) { return drawn[o]; })) return;
            const key = it.gk || it.i;
            if (seen[key]) return;
            seen[key] = 1;
            out.push({ key: key, name: it.n });
        });
    });
    return out;
}
function opHtml() {
    const p = cur();
    const list = wornFem(p);
    if (!list.length) return '';
    const op = p.op || {};
    return '<div class="cl-h">불투명도 <i>여성 체형 옷</i></div>' + list.map(function (x) {
        const v = (Number(op[x.key]) >= 10 && Number(op[x.key]) < 100) ? Math.round(Number(op[x.key])) : 100;
        return rowOf(x.name, '<input type="range" class="cl-op" min="10" max="100" step="10" value="' + v + '" data-k="' + esc_(x.key) + '"'
            + ' style="flex:1;min-width:120px;accent-color:#d9a05a;">'
            + '<b class="cl-opv" style="min-width:42px;text-align:right;font-weight:normal;font-size:12px;">' + v + '%</b>');
    }).join('');
}
