(function extendPick() {
    const _epicPick = epicPick;
    epicPick = function (i) {
        const sc = er && er._sc;
        if (!sc) return;
        const o = sc.opts[i];
        if (!o) return;

        // 미니게임
        if (o.mini) {
            epicMini(o.mini, Object.assign({}, o.miniOpt || {}, {
                done: ok => {
                    if (ok && o.goal) { er.goalDone = true; er.score += EPIC_JOBS[er.job].goal.grade * 1500; }
                    if (ok && o.flag) er.flags[o.flag] = true;
                    if (!ok && o.doomOnLose) { epicDoom(o.doomOnLose); return; }
                    er.idx++;
                    darkBodyEl().innerHTML = darkBox(sc.title + ' — 결과',
                        ok ? o.good : o.bad,
                        epicBar() + darkChoiceBtn('계속한다.', 'epicMap()'));
                }
            }));
            return;
        }

        // 동료 기믹
        if (o.co) {
            epicCoOpen(o.co, Object.assign({ title: sc.title }, o.coOpt || {}, {
                onDone: () => {
                    if (o.goal) { er.goalDone = true; er.score += EPIC_JOBS[er.job].goal.grade * 1500; }
                    if (o.flag) er.flags[o.flag] = true;
                    er.idx++;
                    darkBodyEl().innerHTML = darkBox(sc.title,
                        (o.coOpt && o.coOpt.doneText) || o.good,
                        epicBar() + darkChoiceBtn('계속한다.', 'epicMap()'));
                },
                onFail: () => {
                    if (o.doomOnFail) { epicDoom(o.doomOnFail); return; }
                    er.idx++;
                    darkBodyEl().innerHTML = darkBox(sc.title,
                        (o.coOpt && o.coOpt.failText) || o.bad,
                        epicBar() + darkChoiceBtn('혼자 한다.', 'epicMap()'));
                }
            }));
            return;
        }

        // 즉사 분기
        if (o.doom) {
            const j = EPIC_JOBS[er.job];
            const roll = luckReroll(Math.floor(Math.random() * 20) + 1);
            const bonus = rollDarkBonus(o.kind || j.attr);
            const ok = roll !== 1 && (roll + bonus) >= (o.dc || 13);
            if (ok) {
                er.score += o.p || 600;
                darkRun.success++;
                if (o.flag) er.flags[o.flag] = true;
                if (o.goal) { er.goalDone = true; er.score += j.goal.grade * 1500; }
                er.idx++;
                darkBodyEl().innerHTML = darkBox(sc.title + ' — 결과',
                    `<div style="text-align:center; font-size:26px; font-weight:bold; color:#4CAF50; margin-bottom:12px;">🎲 ${roll} <span style="font-size:13px; color:#888;">(보정 ${bonus >= 0 ? '+' : ''}${bonus} / DC ${o.dc || 13})</span></div>` + o.good,
                    epicBar() + darkChoiceBtn('계속한다.', 'epicMap()'));
            } else {
                darkRun.fail++;
                epicDoom(o.doom);
            }
            return;
        }

        return _epicPick.apply(this, arguments);
    };
})();

