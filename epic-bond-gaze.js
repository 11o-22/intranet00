(function extendCond() {
    const _epicEnter = epicEnter;
    epicEnter = function () {
        if (!er) return;
        const key = er.place;
        const set = EPIC_SCENES[key];
        if (!set) { epicStub(); return; }
        if (!er.seen) er.seen = {};

        const job = er.job, attr = epicAttr();
        const pools = [];
        if (set.job && set.job[job]) pools.push(['j', set.job[job]]);
        if (set.attr && set.attr[attr]) pools.push(['a', set.attr[attr]]);
        if (set.common) pools.push(['c', set.common]);

        for (const [tag, arr] of pools) {
            for (let i = 0; i < arr.length; i++) {
                const id = `${key}:${tag}:${i}`;
                if (er.seen[id]) continue;
                if (arr[i].cond && !arr[i].cond()) continue;
                er.seen[id] = true;
                er._scId = id;
                epicScene(arr[i]);
                return;
            }
        }
        epicStub();
    };
})();

function epicFlagCount() {
    return er && er.flags ? Object.keys(er.flags).length : 0;
}

function epicOpenDeep() {
    if (!er) return;
    er.flags.deepFound = true;
    er.score += 1500;
    if (darkRun.isParty) sendPartyChat(`${currentUser.name} 사원이 지도에 없는 곳을 찾았습니다.`, true);
}

